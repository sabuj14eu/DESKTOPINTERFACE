"""SIGNAL ORIGIN AND LIFECYCLE — where a signal came from and how far it really got.

A SignalMesh signal is a RECOMMENDATION. It is a broker execution only when a broker
trade is linked to it by the journal's own `signal_id`. This module never links by
resemblance (same symbol / price / minute): a look-alike is not evidence.

Every value is read from the signal row or its `raw_payload`; `source` names the field.
What the row does not say is the word UNKNOWN — never a guess.

The five stages the terminal keeps apart:
  A  generated by SignalMesh          signal.created_at
  B  approved                         B1 the ENGINE — SignalMesh's brain council (signal.status / council)
                                      B2 YOU — the user's personal order approval — this terminal has no approval function
                                         in this phase, so it is NOT RECORDED, always
  C  order submitted to the broker    a linked journal row, else SignalMesh's own word `executed`
  D  order filled by the broker       linked journal row with an entry price
  E  position closed                  linked journal row with status closed
"""
from __future__ import annotations

from datetime import timedelta

from .contract import SignalRef
from .normalize import _aware

UNKNOWN = "UNKNOWN"
_SIGNAL_LINK_KEYS = ("signal_id", "signal", "signal_ref")


def _first(signal: dict, payload: dict, signal_keys=(), payload_keys=()) -> dict:
    for k in signal_keys:
        v = signal.get(k)
        if v not in (None, "") and not isinstance(v, (dict, list)):
            return {"value": v if isinstance(v, (int, float, bool)) else str(v), "source": f"signal.{k}"}
    for k in payload_keys:
        v = payload.get(k)
        if v not in (None, "") and not isinstance(v, (dict, list)):
            return {"value": v if isinstance(v, (int, float, bool)) else str(v), "source": f"signal.raw_payload.{k}"}
    return {"value": UNKNOWN, "source": ""}


def _val(v, source: str) -> dict:
    return {"value": UNKNOWN, "source": ""} if v in (None, "") else {"value": v, "source": source}


def linked_trade(signal_id: str, trades: list[dict]) -> dict | None:
    for t in trades:
        if any(str(t.get(k) or "") == signal_id for k in _SIGNAL_LINK_KEYS):
            return t
    return None


def stage_word(status: str, stale: bool, trade: dict | None) -> tuple[str, bool]:
    """(headline, is_broker_execution)"""
    if trade is not None:
        st = str(trade.get("status") or "").lower()
        if st == "closed":
            return "POSITION CLOSED at the broker", True
        if st == "open":
            return "ORDER FILLED at the broker — position open", True
        if st == "pending":
            return "ORDER SUBMITTED to the broker — not filled", True
        return f"broker journal row linked (status {st or UNKNOWN})", True
    if status == "executed":
        return "SignalMesh reports EXECUTED — no broker order is linked to this signal", False
    if status == "rejected":
        return "REJECTED by the SignalMesh brain — never an order", False
    if status == "approved":
        return ("EXPIRED RECOMMENDATION — approved by the brain council, never executed" if stale
                else "RECOMMENDATION ONLY — approved by the brain council, NOT an executed trade"), False
    if status == "pending":
        return ("EXPIRED RECOMMENDATION — was pending, never executed" if stale
                else "RECOMMENDATION ONLY — pending, NOT an executed trade"), False
    return f"signal status {status or UNKNOWN} — not an executed trade", False


def signal_detail(sig: SignalRef, raw: dict, trades: list[dict], ttl_h: float) -> dict:
    payload = raw.get("raw_payload") if isinstance(raw.get("raw_payload"), dict) else {}
    trade = linked_trade(sig.signal_id, trades)
    journal_links = any(any(k in t for k in _SIGNAL_LINK_KEYS) for t in trades)
    no_link = ("the trade journal carries a signal link, and no row names this signal" if journal_links
               else "SignalMesh's trade journal carries no signal link, so a broker trade cannot be tied to this signal")
    headline, is_exec = stage_word(sig.status, sig.stale, trade)

    origin = {
        "signal_id": _val(sig.signal_id, "signal.signal_id"),
        "originating_engine": _first(raw, payload, ("system",), ("sensor_system", "engine")),
        "engine_detail": _first(raw, payload, ("engine", "source", "origin"), ("engine", "sensor_system", "route", "source", "indicator")),
        "strategy_name": _first(raw, payload, ("strategy", "strategy_name"), ("strategy", "strategy_name", "method", "plan_kind", "kind", "mode")),
        "strategy_version": _first(raw, payload, ("strategy_version", "version"), ("strategy_version", "version", "script_version", "build")),
        "symbol": _val(sig.symbol, "signal.symbol"),
        "timeframe": _val(sig.tf, "signal.tf"),
        "direction": _val(sig.direction if sig.direction in ("BUY", "SELL") else "", "signal.direction"),
        "created_at": _val(sig.created_at, "signal.created_at"),
        "entry": _val(sig.entry, "signal.entry"), "sl": _val(sig.sl, "signal.sl"),
        "tp1": _val(sig.tp1, "signal.tp1"), "tp2": _val(sig.tp2, "signal.tp2"),
        "risk_reward": _val(sig.rr, "signal.rr"),
        "confidence": _val(sig.confidence, "signal.confidence"),
        "grade": _val(sig.grade, "signal.grade"),
    }

    structure_words = {k: sig.pine[k] for k in ("trend", "choch", "inducement", "sweep", "htf_align", "loc_zone") if k in sig.pine}
    validation = {
        "structure": {"value": sig.market_structure or UNKNOWN, "source": "signal.market_structure" if sig.market_structure else "",
                      "sensor_words": structure_words, "sensor_source": "signal.raw_payload" if structure_words else ""},
        "news": _first({}, payload, (), ("news_window", "news", "news_risk")),
        "council": ({"value": f"{sig.council_approve}/{sig.council_total} approve", "source": "signal.council"}
                    if sig.council_total else {"value": UNKNOWN, "source": ""}),
        "brain_reason": _val(sig.reason, "signal.reason"),
    }

    created = _aware(sig.created_at)
    invalidation = []
    if sig.sl is not None and sig.direction in ("BUY", "SELL"):
        invalidation.append(f"a 15m close {'below' if sig.direction == 'BUY' else 'above'} SL {sig.sl} kills the setup (engine life rule)")
    if created is not None:
        exp = created + timedelta(hours=ttl_h)
        invalidation.append(f"{'expired' if sig.stale else 'expires'} {exp.isoformat()} — the engine's {ttl_h:g}h signal lifecycle (planner.SIGNAL_FRESH_H)")
    if sig.status == "rejected":
        invalidation.append("rejected by the brain" + (f": {sig.reason}" if sig.reason else ""))
    if not invalidation:
        invalidation.append(UNKNOWN)

    def st(key, label, state, detail, source="", at=None):
        return {"key": key, "label": label, "state": state, "detail": detail, "source": source, "at": at}

    council = (f" · council {sig.council_approve}/{sig.council_total}" if sig.council_total else "")
    if sig.status in ("approved", "executed"):
        b1 = st("council", "B1 · Engine approval — SignalMesh brain council", "DONE", f"status {sig.status}{council}", "signal.status")
    elif sig.status == "rejected":
        b1 = st("council", "B1 · Engine approval — SignalMesh brain council", "REJECTED", f"rejected{council}", "signal.status")
    elif sig.status == "pending":
        b1 = st("council", "B1 · Engine approval — SignalMesh brain council", "NOT_DONE", "pending — not decided", "signal.status")
    else:
        b1 = st("council", "B1 · Engine approval — SignalMesh brain council", "UNKNOWN", f"status {sig.status or UNKNOWN}", "signal.status")
    t_status = str((trade or {}).get("status") or "").lower()
    if trade is not None:
        c = st("submitted", "C · Order submitted to the broker", "DONE", f"journal row #{trade.get('id')} · {t_status}", "trade journal · signal_id", trade.get("open_time"))
        filled = t_status in ("open", "closed") and trade.get("entry") is not None
        d = st("filled", "D · Order filled by the broker", "DONE" if filled else "NOT_DONE",
               f"filled at {trade.get('entry')}" if filled else f"journal status {t_status or UNKNOWN}", "trade journal · entry", trade.get("open_time") if filled else None)
        closed = t_status == "closed"
        e = st("closed", "E · Position closed", "DONE" if closed else "NOT_DONE",
               f"closed at {trade.get('exit')} · P/L {trade.get('profit')}" if closed else "position not closed", "trade journal · status", trade.get("close_time") if closed else None)
    elif sig.status == "executed":
        c = st("submitted", "C · Order submitted to the broker", "REPORTED", "SignalMesh's status says `executed`; " + no_link, "signal.status")
        d = st("filled", "D · Order filled by the broker", "UNKNOWN", no_link)
        e = st("closed", "E · Position closed", "UNKNOWN", no_link)
    else:
        c = st("submitted", "C · Order submitted to the broker", "NOT_RECORDED", f"SignalMesh status is `{sig.status or UNKNOWN}`, not `executed` — no submission recorded", "signal.status")
        d = st("filled", "D · Order filled by the broker", "NOT_RECORDED", "no order, so no fill")
        e = st("closed", "E · Position closed", "NOT_RECORDED", "no position")
    lifecycle = [
        st("generated", "A · Signal generated by SignalMesh", "DONE" if sig.created_at else "UNKNOWN",
           f"by {sig.system or UNKNOWN}", "signal.created_at", sig.created_at),
        b1,
        st("user", "B2 · Your approval — your personal order approval", "NOT_RECORDED",
           "you have not approved anything: this terminal has no order-approval function in this phase (execution disabled). SignalMesh's `approved` is the engine council's decision, never yours"),
        c, d, e,
    ]

    acct = next((trade.get(k) for k in ("account", "account_id", "login") if trade and trade.get(k) not in (None, "")), None)
    from .accounts import mask
    execution = {
        "status": headline,
        "is_broker_execution": is_exec,
        "broker_source": _val("SignalMesh trade journal (MT5 reporter heartbeats)" if trade else "", "trade journal"),
        "account": _val(mask(acct) if acct else "", "trade journal · account"),
        "execution_price": _val(trade.get("entry") if trade and t_status in ("open", "closed") else None, "trade journal · entry"),
        "exit_price": _val(trade.get("exit") if trade and t_status == "closed" else None, "trade journal · exit"),
        "lots": _val(trade.get("lots") if trade else None, "trade journal · lots"),
        "profit": _val(trade.get("profit") if trade and t_status == "closed" else None, "trade journal · profit"),
        "journal_row": trade.get("id") if trade else None,
        "link_rule": "a broker trade belongs to a signal only when the journal row names its signal_id; never matched by symbol, price or time",
        "link_note": "" if trade else no_link,
    }
    return {"signal": sig.model_dump(), "headline": headline, "is_broker_execution": is_exec, "origin": origin,
            "validation": validation, "invalidation": invalidation, "lifecycle": lifecycle, "execution": execution,
            "sensor_payload": sig.pine,
            "fields_seen": {"signal": sorted(k for k in raw if k != "raw_payload"), "raw_payload": sorted(payload)},
            "rule": "every value is read from the signal row or its raw_payload and names its field; a value SignalMesh did not send is UNKNOWN"}
